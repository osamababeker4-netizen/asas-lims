'use strict';
// UI strings are translated; saved values and escaped user content are preserved.
const uiTextMemory = new WeakMap();
const uiAttributeMemory = new WeakMap();
let uiLanguage = localStorage.getItem('asas_lims_language') === 'en' ? 'en' : 'ar';
const uiPattern = new RegExp(Object.keys(UI_TRANSLATIONS).sort((a,b)=>b.length-a.length).map(s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('|'),'g');
function translateUI(value) {
  return String(value == null ? '' : value).replace(uiPattern, function(match,offset,whole) {
    const arabic = /[\u0621-\u064a]/;
    if ((arabic.test(match[0]) && arabic.test(whole[offset-1] || '')) || (arabic.test(match[match.length-1]) && arabic.test(whole[offset+match.length] || ''))) return match;
    return UI_TRANSLATIONS[match];
  });
}
function restoreUserText(value) { return value.replace(/\uE000([0-9a-f]+)\uE001/g,(_,hex)=>String.fromCodePoint(parseInt(hex,16))); }
function applyUI(root, rememberNew=true) {
  const doc=root.ownerDocument || document;
  const walker=doc.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  let node;
  while ((node=walker.nextNode())) {
    const parent=node.parentElement;
    if (!parent || parent.closest('script,style')) continue;
    if(parent.closest('textarea,[translate="no"]')) {node.nodeValue=restoreUserText(node.nodeValue);continue;}
    let record=uiTextMemory.get(node);
    if (!record && rememberNew) {
      const raw=node.nodeValue;
      if(parent.tagName==='OPTION' && !parent.hasAttribute('value')) parent.setAttribute('value',restoreUserText(parent.textContent));
      record={ar:restoreUserText(raw),en:restoreUserText(parent.dataset.en || translateUI(raw))};
      uiTextMemory.set(node,record);
    }
    if(record) node.nodeValue=record[uiLanguage];
  }
  const elements=[...(root.nodeType===1?[root]:[]),...root.querySelectorAll('*')];
  elements.forEach(function(element) {
    // Restore masked entities in values/attributes without translating them.
    for(const attr of element.attributes) if(attr.value.includes('\uE000')) element.setAttribute(attr.name,restoreUserText(attr.value));
    if(element.closest('[translate="no"]')) return;
    let record=uiAttributeMemory.get(element);
    if(!record && rememberNew) {
      record={};
      for(const key of ['placeholder','title','aria-label','alt']) if(element.hasAttribute(key)) {const ar=element.getAttribute(key);record[key]={ar,en:translateUI(ar)};}
      uiAttributeMemory.set(element,record);
    }
    if(record) for(const key of Object.keys(record)) element.setAttribute(key,record[key][uiLanguage]);
  });
}
function setHtml(element,html) {
  // esc() encodes Arabic user data; mask it before translating generated UI.
  element.innerHTML=String(html).replace(/&#x([0-9a-f]+);/gi,(_,hex)=>'\uE000'+hex+'\uE001');
  applyUI(element);
  return html;
}
function setText(element,value) {
  const ar=String(value == null ? '' : value);
  element.textContent=ar;
  if(element.firstChild) uiTextMemory.set(element.firstChild,{ar,en:translateUI(ar)});
  applyUI(element);
  return value;
}
function escUI(value) {return String(value == null?'':value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));}
function setLanguage(lang) {
  uiLanguage=lang==='en'?'en':'ar';
  document.documentElement.lang=uiLanguage;
  document.documentElement.dir=uiLanguage==='en'?'ltr':'rtl';
  localStorage.setItem('asas_lims_language',uiLanguage);
  applyUI(document.body);
  document.title=uiLanguage==='en'?'ASAS LIMS | Laboratory and project management':'أساس LIMS | إدارة المختبر والمشاريع';
}
